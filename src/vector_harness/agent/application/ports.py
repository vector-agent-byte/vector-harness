"""Persistence contracts consumed by the application layer."""

from pathlib import Path
from collections.abc import Callable
from typing import Protocol


class SessionRepository(Protocol):
    def is_session_id(self, value: str) -> bool: ...

    def session_path(self, workspace: Path, session_id: str) -> Path: ...

    def create_session(self, workspace: Path) -> str: ...

    def list_sessions(self, workspace: Path) -> list[dict]: ...

    def read_session_view(self, workspace: Path, session_id: str) -> dict: ...

    def session_version(self, workspace: Path, session_id: str) -> tuple: ...

    def delete_session(self, workspace: Path, session_id: str) -> None: ...

    def session_run(self, workspace: Path, session_id: str) -> tuple[float | None, int | None]: ...

    def session_mode(self, workspace: Path, session_id: str) -> str | None: ...

    def set_session_mode(self, workspace: Path, session_id: str, mode: str) -> None: ...

    def session_skill(self, workspace: Path, session_id: str) -> str | None: ...

    def session_skills(self, workspace: Path, session_id: str) -> list[str] | None: ...

    def set_session_skills(self, workspace: Path, session_id: str, names: list[str] | None) -> None: ...


class TaskMetadataRepository(Protocol):
    def read(self, session_id: str) -> dict | None: ...

    def create(self, session_id: str, kind: str, config: dict, **extra) -> dict: ...

    def update(self, session_id: str, **changes) -> dict: ...

    def remove(self, session_id: str) -> None: ...


class RunConfiguration(Protocol):
    plan: bool
    reflect: bool
    subagents: bool


class RunCoordinator(Protocol):
    settings: RunConfiguration
    running_id: str | None

    def acquire(self) -> bool: ...

    def release(self) -> None: ...

    def stop(self, session_id: str) -> bool: ...

    def run(self, session_id: str, session_path: Path, text: str, *, plan: bool,
            reflect: bool, subagents: bool, emit: Callable, ready: Callable) -> tuple[str, str]: ...
